export const FONT_CHARS = Object.keys(GLYPHS).join('');

// Text als ein Linienzug in Schrift-Einheiten (y nach oben, Grundlinie 0) -> {pts, width}
export function textPath(text) {
  const pts = [];
  let x = 0;
  let width = 0;
  for (const ch of String(text).toUpperCase()) {
    const g = GLYPHS[ch] || [2, []];
    for (const [gx, gy] of g[1]) pts.push([x + gx, gy]);
    width = x + g[0];
    x = width + GAP;
  }
  return { pts, width };
}
